export function getStrategieAttaccantiByCategoria(categoria) {
  if (!categoria || categoria === "Tutte") return STRATEGIE_GENERALI_ATTACCANTI;
  const tagsAmmessi = CATEGORIA_TAG_MAP[categoria] || [];
  return STRATEGIE_GENERALI_ATTACCANTI.filter((s) =>
    s.tags.some((t) => tagsAmmessi.includes(t))
  );
}
