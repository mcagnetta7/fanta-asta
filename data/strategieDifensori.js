export function getStrategieDifensoriByCategoria(categoria) {
  if (!categoria || categoria === "Tutte") return STRATEGIE_GENERALI_DIFENSORI;
  const tagsAmmessi = CATEGORIA_TAG_MAP[categoria] || [];
  return STRATEGIE_GENERALI_DIFENSORI.filter(
    (s) => s.tags.some((t) => tagsAmmessi.includes(t)) || s.categoria === categoria
  );
}
